export function normalizeLanguage(input?: string | null): Language | null {
  if (!input) return null;
  const cleaned = input.trim().toLowerCase();
  if (!cleaned) return null;
  const base = cleaned.split(/[-_]/)[0];
  if (base === "en" || base === "es" || base === "ja") {
    return base;
  }
  return null;
}

export function resolveInitialLanguage(options?: {
  stored?: string | null;
  browserLanguages?: readonly string[];
}): Language {
  const fromStored = normalizeLanguage(options?.stored);
  if (fromStored) return fromStored;

  const browserList = options?.browserLanguages ?? [];
  for (const candidate of browserList) {
    const normalized = normalizeLanguage(candidate);
    if (normalized) return normalized;
  }
  return "en";
}

