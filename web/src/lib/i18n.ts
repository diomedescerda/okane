const ENGLISH_CATEGORY_NAME_TO_SLUG = new Map<string, string>(
  Object.entries(CATEGORY_TRANSLATIONS.en).map(([slug, name]) => [name.toLowerCase(), slug]),
);

export function translateCategoryName(
  lang: Language,
  slug?: string | null,
  fallbackName?: string | null,
): string {
  if (slug) {
    const bySlug = CATEGORY_TRANSLATIONS[lang]?.[slug];
    if (bySlug) return bySlug;
  }
  if (fallbackName) {
    const matchedSlug = ENGLISH_CATEGORY_NAME_TO_SLUG.get(fallbackName.trim().toLowerCase());
    if (matchedSlug) {
      const byMatched = CATEGORY_TRANSLATIONS[lang]?.[matchedSlug];
      if (byMatched) return byMatched;
    }
    return fallbackName;
  }
  return translate(lang, "common.uncategorized");
}

